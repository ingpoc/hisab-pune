export function getLocality(id: string): Locality | undefined {
  return localities.find((l) => l.id === id);
}

export function nearestLocality(lat: number, lng: number): Locality {
  let best = localities[0];
  let bestD = Infinity;
  for (const loc of localities) {
    const d = (loc.lat - lat) ** 2 + (loc.lng - lng) ** 2;
    if (d < bestD) {
      bestD = d;
      best = loc;
    }
  }
  return best;
}
